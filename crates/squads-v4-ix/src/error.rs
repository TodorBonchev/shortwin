//! Squads v4's `MultisigError` (Anchor custom error `6000 + variant index`; the IDL's `errors`,
//! checked in `tests/idl.rs`).

/// `MultisigError` as Squads 2.1.0 numbers it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum MultisigError {
    DuplicateMember = 6000,
    EmptyMembers,
    TooManyMembers,
    InvalidThreshold,
    Unauthorized,
    NotAMember,
    InvalidTransactionMessage,
    StaleProposal,
    InvalidProposalStatus,
    InvalidTransactionIndex,
    AlreadyApproved,
    AlreadyRejected,
    AlreadyCancelled,
    InvalidNumberOfAccounts,
    InvalidAccount,
    RemoveLastMember,
    NoVoters,
    NoProposers,
    NoExecutors,
    InvalidStaleTransactionIndex,
    NotSupportedForControlled,
    TimeLockNotReleased,
    NoActions,
    MissingAccount,
    InvalidMint,
    InvalidDestination,
    SpendingLimitExceeded,
    DecimalsMismatch,
    UnknownPermission,
    ProtectedAccount,
    TimeLockExceedsMaxAllowed,
    IllegalAccountOwner,
    RentReclamationDisabled,
    InvalidRentCollector,
    ProposalForAnotherMultisig,
    TransactionForAnotherMultisig,
    TransactionNotMatchingProposal,
    TransactionNotLastInBatch,
    BatchNotEmpty,
    SpendingLimitInvalidAmount,
    InvalidInstructionArgs,
    FinalBufferHashMismatch,
    FinalBufferSizeExceeded,
    FinalBufferSizeMismatch,
    MultisigCreateDeprecated,
}

impl MultisigError {
    /// Every variant, in code order.
    pub const ALL: [Self; 45] = [
        Self::DuplicateMember,
        Self::EmptyMembers,
        Self::TooManyMembers,
        Self::InvalidThreshold,
        Self::Unauthorized,
        Self::NotAMember,
        Self::InvalidTransactionMessage,
        Self::StaleProposal,
        Self::InvalidProposalStatus,
        Self::InvalidTransactionIndex,
        Self::AlreadyApproved,
        Self::AlreadyRejected,
        Self::AlreadyCancelled,
        Self::InvalidNumberOfAccounts,
        Self::InvalidAccount,
        Self::RemoveLastMember,
        Self::NoVoters,
        Self::NoProposers,
        Self::NoExecutors,
        Self::InvalidStaleTransactionIndex,
        Self::NotSupportedForControlled,
        Self::TimeLockNotReleased,
        Self::NoActions,
        Self::MissingAccount,
        Self::InvalidMint,
        Self::InvalidDestination,
        Self::SpendingLimitExceeded,
        Self::DecimalsMismatch,
        Self::UnknownPermission,
        Self::ProtectedAccount,
        Self::TimeLockExceedsMaxAllowed,
        Self::IllegalAccountOwner,
        Self::RentReclamationDisabled,
        Self::InvalidRentCollector,
        Self::ProposalForAnotherMultisig,
        Self::TransactionForAnotherMultisig,
        Self::TransactionNotMatchingProposal,
        Self::TransactionNotLastInBatch,
        Self::BatchNotEmpty,
        Self::SpendingLimitInvalidAmount,
        Self::InvalidInstructionArgs,
        Self::FinalBufferHashMismatch,
        Self::FinalBufferSizeExceeded,
        Self::FinalBufferSizeMismatch,
        Self::MultisigCreateDeprecated,
    ];

    /// The custom error code.
    pub fn code(self) -> u32 {
        self as u32
    }
}
